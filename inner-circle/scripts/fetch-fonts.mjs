/**
 * Downloads the web fonts the app uses and writes a self-hosted stylesheet.
 *
 * Inner Circle previously loaded its fonts from Google Fonts, which discloses
 * the visitor's IP address to Google on every page load — undesirable for a
 * mental-health app. Running this script pins the same fonts locally instead.
 *
 *   node scripts/fetch-fonts.mjs
 *
 * It fetches the Google Fonts CSS, keeps only the subsets the app needs
 * (latin, latin-ext, devanagari, kannada), downloads each `.woff2` into
 * `client/public/fonts/` and writes `client/src/styles/fonts.css` with local
 * `url()` references. Re-run it to refresh the fonts.
 */

import { mkdir, writeFile, readdir, rm } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const GF_URL =
  'https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght@9..144,500;9..144,600;9..144,700' +
  '&family=Nunito:ital,wght@0,400;0,500;0,600;0,700;0,800;1,400' +
  '&family=Noto+Sans+Devanagari:wght@400;500;600;700' +
  '&family=Noto+Sans+Kannada:wght@400;500;600;700&display=swap'

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36'

const KEEP_SUBSETS = new Set(['latin', 'latin-ext', 'devanagari', 'kannada'])

const here = dirname(fileURLToPath(import.meta.url))
const fontsDir = join(here, '..', 'client', 'public', 'fonts')
const cssFile = join(here, '..', 'client', 'src', 'styles', 'fonts.css')

const slug = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')

const field = (block, name) => {
  const match = block.match(new RegExp(`${name}:\\s*([^;]+);`))
  return match ? match[1].trim() : ''
}

async function main() {
  console.log('Fetching Google Fonts CSS…')
  const response = await fetch(GF_URL, { headers: { 'User-Agent': UA } })
  if (!response.ok) throw new Error(`Google Fonts responded ${response.status}`)
  const css = await response.text()

  const blocks = [...css.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)]
  if (blocks.length === 0) throw new Error('No @font-face blocks found in the CSS.')

  await rm(fontsDir, { recursive: true, force: true })
  await mkdir(fontsDir, { recursive: true })
  await mkdir(dirname(cssFile), { recursive: true })

  const rules = []
  let downloaded = 0

  for (const [, subset, block] of blocks) {
    if (!KEEP_SUBSETS.has(subset)) continue

    const urlMatch = block.match(/url\((https:\/\/[^)]+\.woff2)\)/)
    if (!urlMatch) continue

    const family = field(block, 'font-family').replace(/['"]/g, '')
    const style = field(block, 'font-style') || 'normal'
    const weight = field(block, 'font-weight') || '400'
    const unicodeRange = field(block, 'unicode-range')

    const file = `${slug(family)}-${slug(weight)}-${slug(style)}-${subset}.woff2`
    const fontResponse = await fetch(urlMatch[1], { headers: { 'User-Agent': UA } })
    if (!fontResponse.ok) throw new Error(`Failed to download ${urlMatch[1]} (${fontResponse.status})`)
    const bytes = Buffer.from(await fontResponse.arrayBuffer())
    await writeFile(join(fontsDir, file), bytes)
    downloaded += 1
    console.log(`  saved ${file} (${bytes.length} bytes)`)

    rules.push(
      [
        '/* ' + subset + ' */',
        '@font-face {',
        `  font-family: '${family}';`,
        `  font-style: ${style};`,
        `  font-weight: ${weight};`,
        '  font-display: swap;',
        `  src: url('/fonts/${file}') format('woff2');`,
        unicodeRange ? `  unicode-range: ${unicodeRange};` : null,
        '}',
      ]
        .filter(Boolean)
        .join('\n'),
    )
  }

  const header = [
    '/*',
    ' * Self-hosted fonts — generated by `node scripts/fetch-fonts.mjs`.',
    ' * Do not edit by hand; re-run the script instead.',
    ` * ${downloaded} files in client/public/fonts/.`,
    ' */',
    '',
  ].join('\n')

  await writeFile(cssFile, header + rules.join('\n\n') + '\n', 'utf8')

  const files = await readdir(fontsDir)
  console.log(`Done. ${downloaded} font files, ${files.length} in public/fonts, CSS written to src/styles/fonts.css.`)
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
